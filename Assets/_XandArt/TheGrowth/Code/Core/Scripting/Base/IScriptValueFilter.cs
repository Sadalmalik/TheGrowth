namespace TheGrowth.Core.Scripting
{
    /// <summary>
    /// Ограничение значения параметра шаблона: атрибут на поле команды, кондишена или эвалуатора, реализующий этот
    /// интерфейс. Парсер проверяет каждое разобранное значение параметра (у списка — каждый элемент); нарушение — ошибка
    /// разбора. Пример — <c>[ModelKind]</c> у параметра-конфига сущности.
    /// </summary>
    public interface IScriptValueFilter
    {
        /// <summary>null — значение подходит; иначе текст ошибки. Значение null (заглушка резолвера) подходит.</summary>
        string Check(object value);
    }
}
